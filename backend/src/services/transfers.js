import { randomUUID } from "node:crypto";
import db, { isUniqueConstraint, withTransaction } from "../db.js";
import { badRequest, conflict, notFound } from "../errors.js";
import { toPaise } from "../money.js";
import { serializeTransfer } from "../serializers.js";
import { requireAccount } from "./accounts.js";
import { applyLedgerEntry } from "./transactions.js";

const insertTransfer = db.prepare(`
  INSERT INTO transfers (
    id, from_account_id, to_account_id, amount_paise, description,
    reference_id, debit_transaction_id, credit_transaction_id, created_at
  ) VALUES (
    @id, @from_account_id, @to_account_id, @amount_paise, @description,
    @reference_id, @debit_transaction_id, @credit_transaction_id, @created_at
  )
`);

const findTransferByReference = db.prepare(`
  SELECT *
  FROM transfers
  WHERE reference_id = ?
`);

const getTransferByIdStmt = db.prepare(`
  SELECT *
  FROM transfers
  WHERE id = ?
`);

function executeTransfer({ fromAccountId, toAccountId, amountPaise, description, referenceId }) {
  const existing = findTransferByReference.get(referenceId);
  if (existing) {
    throw conflict("DUPLICATE_TRANSFER", "A transfer with this reference_id already exists.", {
      transfer: serializeTransfer(existing),
    });
  }

  if (fromAccountId === toAccountId) {
    throw badRequest("INVALID_TRANSFER", "Source and destination accounts must be different.");
  }

  requireAccount(fromAccountId);
  requireAccount(toAccountId);

  const debit = applyLedgerEntry({
    accountId: fromAccountId,
    type: "debit",
    amountPaise,
    description: description || `Transfer to ${toAccountId}`,
    referenceId: `${referenceId}:debit`,
  });

  const credit = applyLedgerEntry({
    accountId: toAccountId,
    type: "credit",
    amountPaise,
    description: description || `Transfer from ${fromAccountId}`,
    referenceId: `${referenceId}:credit`,
  });

  const transfer = {
    id: randomUUID(),
    from_account_id: fromAccountId,
    to_account_id: toAccountId,
    amount_paise: amountPaise,
    description,
    reference_id: referenceId,
    debit_transaction_id: debit.id,
    credit_transaction_id: credit.id,
    created_at: new Date().toISOString(),
  };

  try {
    insertTransfer.run(transfer);
  } catch (error) {
    if (isUniqueConstraint(error)) {
      const duplicate = findTransferByReference.get(referenceId);
      if (duplicate) {
        throw conflict("DUPLICATE_TRANSFER", "A transfer with this reference_id already exists.", {
          transfer: serializeTransfer(duplicate),
        });
      }
    }
    throw error;
  }

  return serializeTransfer(transfer);
}

export function createTransfer(payload) {
  if (!payload || typeof payload !== "object" || Array.isArray(payload)) {
    throw badRequest("INVALID_REQUEST_BODY", "Request body must be a JSON object.");
  }

  if (payload.id !== undefined || payload.created_at !== undefined) {
    throw badRequest(
      "READ_ONLY_FIELD",
      "id and created_at are generated by the system and cannot be set by the client.",
    );
  }

  const fromAccountId =
    typeof payload.from_account_id === "string" ? payload.from_account_id.trim() : "";
  const toAccountId =
    typeof payload.to_account_id === "string" ? payload.to_account_id.trim() : "";

  if (!fromAccountId) {
    throw badRequest("INVALID_ACCOUNT_ID", "from_account_id is required.");
  }
  if (!toAccountId) {
    throw badRequest("INVALID_ACCOUNT_ID", "to_account_id is required.");
  }

  const rawRef = payload.reference_id;
  const referenceId =
    (typeof rawRef === "string" || typeof rawRef === "number")
      ? String(rawRef).trim()
      : "";
  if (!referenceId) {
    throw badRequest("INVALID_REFERENCE_ID", "reference_id is required.");
  }
  if (referenceId.length > 255) {
    throw badRequest("INVALID_REFERENCE_ID", "reference_id cannot exceed 255 characters.");
  }

  const description =
    payload.description === undefined || payload.description === null
      ? ""
      : String(payload.description).trim();

  if (description.length > 1000) {
    throw badRequest("INVALID_DESCRIPTION", "description cannot exceed 1000 characters.");
  }

  const amountPaise = toPaise(payload.amount);

  return withTransaction(() =>
    executeTransfer({
      fromAccountId,
      toAccountId,
      amountPaise,
      description,
      referenceId,
    }),
  );
}

export function getTransfer(id) {
  if (!id || typeof id !== "string" || !id.trim()) {
    throw badRequest("INVALID_TRANSFER_ID", "A valid transfer ID is required.");
  }
  const row = getTransferByIdStmt.get(id.trim());
  if (!row) {
    throw notFound("TRANSFER_NOT_FOUND", `Transfer '${id}' was not found.`);
  }
  return serializeTransfer(row);
}
