import { randomUUID } from "node:crypto";
import db, { isUniqueConstraint, withTransaction } from "../db.js";
import { badRequest, conflict, notFound, unprocessable } from "../errors.js";
import { toPaise } from "../money.js";
import { serializeTransaction } from "../serializers.js";
import { requireAccount } from "./accounts.js";

const insertTransaction = db.prepare(`
  INSERT INTO transactions (
    id, account_id, type, amount_paise, description, reference_id, created_at
  ) VALUES (
    @id, @account_id, @type, @amount_paise, @description, @reference_id, @created_at
  )
`);

const updateBalance = db.prepare(`
  UPDATE accounts
  SET balance_paise = balance_paise + @delta
  WHERE id = @id
`);

const findByReference = db.prepare(`
  SELECT id, account_id, type, amount_paise, description, reference_id, created_at
  FROM transactions
  WHERE account_id = ? AND reference_id = ?
`);

const getTransactionByIdStmt = db.prepare(`
  SELECT id, account_id, type, amount_paise, description, reference_id, created_at
  FROM transactions
  WHERE id = ?
`);

const countTransactions = db.prepare(`
  SELECT COUNT(*) AS total
  FROM transactions
  WHERE account_id = @account_id
    AND (@type IS NULL OR type = @type)
`);

const listTransactionsStmt = db.prepare(`
  SELECT id, account_id, type, amount_paise, description, reference_id, created_at
  FROM transactions
  WHERE account_id = @account_id
    AND (@type IS NULL OR type = @type)
  ORDER BY created_at DESC, rowid DESC
  LIMIT @limit OFFSET @offset
`);

function normalizeTransactionInput(payload) {
  if (!payload || typeof payload !== "object" || Array.isArray(payload)) {
    throw badRequest("INVALID_REQUEST_BODY", "Request body must be a JSON object.");
  }

  if (payload.id !== undefined || payload.created_at !== undefined) {
    throw badRequest(
      "READ_ONLY_FIELD",
      "id and created_at are generated by the system and cannot be set by the client.",
    );
  }

  const type = typeof payload.type === "string" ? payload.type.trim().toLowerCase() : "";
  if (type !== "credit" && type !== "debit") {
    throw badRequest("INVALID_TRANSACTION_TYPE", "Transaction type must be either 'credit' or 'debit'.");
  }

  const amountPaise = toPaise(payload.amount);

  const rawRef = payload.reference_id;
  const referenceId =
    (typeof rawRef === "string" || typeof rawRef === "number")
      ? String(rawRef).trim()
      : "";
  if (!referenceId) {
    throw badRequest("INVALID_REFERENCE_ID", "reference_id is required.");
  }
  if (referenceId.length > 255) {
    throw badRequest("INVALID_REFERENCE_ID", "reference_id cannot exceed 255 characters.");
  }

  const description =
    payload.description === undefined || payload.description === null
      ? ""
      : String(payload.description).trim();

  if (description.length > 1000) {
    throw badRequest("INVALID_DESCRIPTION", "description cannot exceed 1000 characters.");
  }

  return { type, amountPaise, referenceId, description };
}

export function applyLedgerEntry({
  accountId,
  type,
  amountPaise,
  description,
  referenceId,
}) {
  const existing = findByReference.get(accountId, referenceId);
  if (existing) {
    throw conflict("DUPLICATE_TRANSACTION", "A transaction with this reference_id already exists for the account.", {
      transaction: serializeTransaction(existing),
    });
  }

  const account = requireAccount(accountId);
  const currentPaise = account.balance_paise !== undefined ? account.balance_paise : account.balance_cents;
  const delta = type === "credit" ? amountPaise : -amountPaise;

  if (type === "debit" && currentPaise < amountPaise) {
    throw unprocessable(
      "INSUFFICIENT_BALANCE",
      "Debit rejected because the account does not have sufficient balance.",
      {
        account_id: account.id,
        balance: currentPaise / 100,
        attempted_amount: amountPaise / 100,
      },
    );
  }

  const transaction = {
    id: randomUUID(),
    account_id: accountId,
    type,
    amount_paise: amountPaise,
    description,
    reference_id: referenceId,
    created_at: new Date().toISOString(),
  };

  try {
    insertTransaction.run(transaction);
    updateBalance.run({ id: accountId, delta });
  } catch (error) {
    if (isUniqueConstraint(error)) {
      const duplicate = findByReference.get(accountId, referenceId);
      if (duplicate) {
        throw conflict(
          "DUPLICATE_TRANSACTION",
          "A transaction with this reference_id already exists for the account.",
          { transaction: serializeTransaction(duplicate) },
        );
      }
    }
    throw error;
  }

  return serializeTransaction(transaction);
}

export function createTransaction(accountId, payload) {
  requireAccount(accountId);

  if (payload?.account_id !== undefined && String(payload.account_id).trim() !== accountId) {
    throw badRequest(
      "INVALID_ACCOUNT_ID",
      "account_id in request body does not match the account ID in the URL.",
    );
  }

  const input = normalizeTransactionInput(payload);

  return withTransaction(() => applyLedgerEntry({
    accountId,
    type: input.type,
    amountPaise: input.amountPaise,
    description: input.description,
    referenceId: input.referenceId,
  }));
}

export function getTransaction(id) {
  if (!id || typeof id !== "string" || !id.trim()) {
    throw badRequest("INVALID_TRANSACTION_ID", "A valid transaction ID is required.");
  }
  const row = getTransactionByIdStmt.get(id.trim());
  if (!row) {
    throw notFound("TRANSACTION_NOT_FOUND", `Transaction '${id}' was not found.`);
  }
  return serializeTransaction(row);
}

export function getTransactionHistory(accountId, query = {}) {
  requireAccount(accountId);

  const typeRaw = query.type;
  let type = null;
  if (typeRaw !== undefined && typeRaw !== "") {
    const normalized = String(typeRaw).trim().toLowerCase();
    if (normalized !== "credit" && normalized !== "debit") {
      throw badRequest("INVALID_TRANSACTION_TYPE", "Filter type must be either 'credit' or 'debit'.");
    }
    type = normalized;
  }

  const page = parsePaginationInt(query.page, 1, "page");
  const limit = parsePaginationInt(query.limit, 10, "limit");
  if (page < 1) {
    throw badRequest("INVALID_PAGINATION", "page must be an integer greater than or equal to 1.");
  }
  if (limit < 1 || limit > 100) {
    throw badRequest("INVALID_PAGINATION", "limit must be an integer between 1 and 100.");
  }

  const { total } = countTransactions.get({ account_id: accountId, type: type ?? null });
  const totalPages = total === 0 ? 0 : Math.ceil(total / limit);
  const offset = (page - 1) * limit;
  const items = listTransactionsStmt.all({
    account_id: accountId,
    type: type ?? null,
    limit,
    offset,
  });

  return {
    data: items.map(serializeTransaction),
    pagination: {
      page,
      current_page: page,
      limit,
      page_size: limit,
      total_records: total,
      total_pages: totalPages,
    },
  };
}

function parsePaginationInt(value, fallback, field) {
  if (value === undefined || value === "") {
    return fallback;
  }

  const str = String(value).trim();
  if (!/^\d+$/.test(str)) {
    throw badRequest("INVALID_PAGINATION", `${field} must be a positive integer.`);
  }

  return Number(str);
}

export { findByReference };
