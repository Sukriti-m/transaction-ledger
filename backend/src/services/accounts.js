import { randomUUID } from "node:crypto";
import db from "../db.js";
import { badRequest, notFound } from "../errors.js";
import { serializeAccount, serializeBalance } from "../serializers.js";

const insertAccount = db.prepare(`
  INSERT INTO accounts (id, name, balance_paise, created_at)
  VALUES (@id, @name, 0, @created_at)
`);

const getAccountById = db.prepare(`
  SELECT id, name, balance_paise, created_at
  FROM accounts
  WHERE id = ?
`);

const listAccountsStmt = db.prepare(`
  SELECT id, name, balance_paise, created_at
  FROM accounts
  ORDER BY created_at DESC
`);

export function createAccount(payload) {
  if (
    payload.balance !== undefined ||
    payload.balance_paise !== undefined ||
    payload.balance_cents !== undefined
  ) {
    throw badRequest(
      "INITIAL_BALANCE_NOT_ALLOWED",
      "Initial balance cannot be set by the client. New accounts always start at 0.",
    );
  }

  if (payload.id !== undefined || payload.created_at !== undefined) {
    throw badRequest(
      "READ_ONLY_FIELD",
      "id and created_at are generated by the system and cannot be set by the client.",
    );
  }

  const trimmed = typeof payload.name === "string" ? payload.name.trim() : "";
  if (!trimmed) {
    throw badRequest("INVALID_ACCOUNT_NAME", "Account name is required.");
  }

  if (trimmed.length > 255) {
    throw badRequest("INVALID_ACCOUNT_NAME", "Account name cannot exceed 255 characters.");
  }

  const account = {
    id: randomUUID(),
    name: trimmed,
    created_at: new Date().toISOString(),
  };

  insertAccount.run(account);
  return serializeAccount({ ...account, balance_paise: 0 });
}

export function requireAccount(id) {
  if (!id || typeof id !== "string" || !id.trim()) {
    throw badRequest("INVALID_ACCOUNT_ID", "A valid account ID is required.");
  }

  const account = getAccountById.get(id.trim());
  if (!account) {
    throw notFound("ACCOUNT_NOT_FOUND", `Account '${id}' was not found.`);
  }
  return account;
}

export function getAccount(id) {
  return serializeAccount(requireAccount(id));
}

export function getAccountBalance(id) {
  return serializeBalance(requireAccount(id));
}

export function listAccounts() {
  return listAccountsStmt.all().map(serializeAccount);
}
